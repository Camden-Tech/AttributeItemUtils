package com.baddcamden.attributeitemutils.gear;

/**
 * Enumerates the gear slots supported by the plugin when constructing equipment kits.
 */
public enum GearSlot {
    /** Helmet slot for head armor pieces. */
    HELMET,
    /** Chestplate slot for torso armor. */
    CHESTPLATE,
    /** Leggings slot for leg armor. */
    LEGGINGS,
    /** Boots slot for foot armor. */
    BOOTS,
    /** Primary hand slot for tools or weapons. */
    HAND,
    /** Off-hand slot for shields or secondary items. */
    OFF_HAND
}
