package com.baddcamden.attributeitemutils.gear;

/**
 * Enumeration of equipment slots relevant to kit generation. Slots are converted to lower-case
 * configuration keys when reading {@code Gear.yml} lists.
 */
public enum GearSlot {
    HELMET,
    CHESTPLATE,
    LEGGINGS,
    BOOTS,
    HAND,
    OFF_HAND
}
