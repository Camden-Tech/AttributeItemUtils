package com.baddcamden.attributeitemutils.gear;

/**
 * Enumerates supported equipment slots when assembling gear kits.
 */
public enum GearSlot {
    /** Helmet slot. */
    HELMET,
    /** Chestplate slot. */
    CHESTPLATE,
    /** Leggings slot. */
    LEGGINGS,
    /** Boots slot. */
    BOOTS,
    /** Main hand slot. */
    HAND,
    /** Off hand slot. */
    OFF_HAND
}
